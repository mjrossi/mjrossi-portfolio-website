// One-off regenerator for the two committed assets behind /card:
//
//   src/lib/card-qr.js     — the QR code on the card's back face, as path data
//   src/lib/card-photo.js  — the vCard PHOTO, a small base64 JPEG
//
// One-off rather than a build step, on the make-og.mjs model: neither input
// moves. The QR code encodes a URL that must never change — printed cards will
// carry it — and the photo changes when src/assets/profile.jpg does, which is
// also when `just og` is due. Generating either on every build would buy
// nothing and put `qrcode` in the build path.
//
// Run from the project root:
//   just card-assets
import QRCode from 'qrcode';
import sharp from 'sharp';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// ── QR ────────────────────────────────────────────────
//
// `/card`, not the home page: a scan should land on the page with the
// "Add to contacts" link, which is the whole point of holding a phone up.
const QR_URL = 'https://mjrossi.com/card';

// The spec's minimum quiet zone. Smaller and some scanners never find the
// finder patterns; the page draws the tile across all of it.
const QUIET = 4;

// M: version 2 (25 × 25) for this URL. H would buy damage tolerance a screen
// never needs, at the cost of a denser code — and density is what makes a
// phone-to-phone scan fail.
const qr = QRCode.create(QR_URL, { errorCorrectionLevel: 'M' });
const n = qr.modules.size;
const size = n + QUIET * 2;

// One subpath per horizontal run of dark modules. No colour here: the page
// fills the path from a token, so the generated file carries geometry only.
let path = '';
for (let row = 0; row < n; row++) {
  let col = 0;
  while (col < n) {
    if (!qr.modules.get(row, col)) { col++; continue; }
    const start = col;
    while (col < n && qr.modules.get(row, col)) col++;
    path += `M${start + QUIET} ${row + QUIET}h${col - start}v1h-${col - start}z`;
  }
}

writeFileSync(
  resolve('src/lib/card-qr.js'),
  `// GENERATED by scripts/make-card-assets.mjs — do not edit; run \`just card-assets\`.
//
// The QR code on /card's back face: version ${qr.version}, error correction M,
// a ${QUIET}-module quiet zone included in QR_SIZE. Geometry only — the page
// colours it from --qr-ink on --qr-tile, which stay Paper in both themes.
// src/lib/card-qr.test.js decodes it.

export const QR_URL = ${JSON.stringify(QR_URL)};
export const QR_QUIET = ${QUIET};
export const QR_SIZE = ${size};
export const QR_PATH =
  ${JSON.stringify(path)};
`,
);
console.log(`wrote src/lib/card-qr.js (version ${qr.version}, ${size} × ${size} modules)`);

// ── Photo ─────────────────────────────────────────────
//
// 256 px is what Contacts displays at; anything larger is weight every
// recipient downloads for nothing. Inlined as base64 because vCard 3.0's
// `PHOTO;ENCODING=b` is the form iOS, Android and Outlook all read — a
// `PHOTO;VALUE=uri` pointing back here is ignored by several of them.
const jpeg = await sharp(resolve('src/assets/profile.jpg'))
  .resize(256, 256, { fit: 'cover' })
  .jpeg({ quality: 80, mozjpeg: true })
  .toBuffer();

writeFileSync(
  resolve('src/lib/card-photo.js'),
  `// GENERATED by scripts/make-card-assets.mjs — do not edit; run \`just card-assets\`.
//
// The vCard PHOTO: src/assets/profile.jpg at 256 × 256, JPEG, base64.

export const PHOTO_JPEG_BASE64 =
  ${JSON.stringify(jpeg.toString('base64'))};
`,
);
console.log(`wrote src/lib/card-photo.js (${jpeg.length} bytes JPEG)`);
