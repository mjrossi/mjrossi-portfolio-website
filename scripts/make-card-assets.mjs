// One-off regenerator for /card's two committed assets, src/lib/card-qr.js
// (the QR on /card/qr, as path data) and src/lib/card-photo.js (the vCard
// PHOTO). Not a build step: the QR's URL must never change — printed cards
// carry it — and the photo changes only by hand.
//
//   just card-assets
import QRCode from 'qrcode';
import sharp from 'sharp';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// ── QR ────────────────────────────────────────────────
//
//
// Encodes `/card`, the page with "Add to contacts".
const QR_URL = 'https://mjrossi.com/card';

// The spec's minimum quiet zone; smaller and some scanners never find it.
const QUIET = 4;

// M (version 2, 25 × 25). H's damage tolerance is useless on a screen and
// the extra density is what makes phone-to-phone scans fail.
const qr = QRCode.create(QR_URL, { errorCorrectionLevel: 'M' });
const n = qr.modules.size;
const size = n + QUIET * 2;

// One subpath per run of dark modules. Geometry only; the page colours it.
let path = '';
for (let row = 0; row < n; row++) {
  let col = 0;
  while (col < n) {
    if (!qr.modules.get(row, col)) { col++; continue; }
    const start = col;
    while (col < n && qr.modules.get(row, col)) col++;
    path += `M${start + QUIET} ${row + QUIET}h${col - start}v1h-${col - start}z`;
  }
}

writeFileSync(
  resolve('src/lib/card-qr.js'),
  `// GENERATED by scripts/make-card-assets.mjs — do not edit; run \`just card-assets\`.
//
// The QR code on /card/qr (it encodes /card): version ${qr.version}, error correction M,
// a ${QUIET}-module quiet zone included in QR_SIZE. Geometry only — the page
// colours it from --qr-ink on --qr-tile, which stay Paper in both themes.
// src/lib/card-qr.test.js decodes it.

export const QR_URL = ${JSON.stringify(QR_URL)};
export const QR_QUIET = ${QUIET};
export const QR_SIZE = ${size};
export const QR_PATH =
  ${JSON.stringify(path)};
`,
);
console.log(`wrote src/lib/card-qr.js (version ${qr.version}, ${size} × ${size} modules)`);

// ── Photo ─────────────────────────────────────────────
//
//
// 256 px, what Contacts displays. Base64 because `PHOTO;ENCODING=b` is what
// iOS, Android and Outlook all read. contact-photo.jpg, not profile.jpg (which
// is pre-masked to a circle): a square crop with the camera's GPS EXIF
// stripped. Baseline, not progressive, for older importers — so no mozjpeg,
// which sharp makes progressive regardless.
const jpeg = await sharp(resolve('src/assets/contact-photo.jpg'))
  .resize(256, 256, { fit: 'cover' })
  .jpeg({ quality: 80 })
  .toBuffer();

writeFileSync(
  resolve('src/lib/card-photo.js'),
  `// GENERATED by scripts/make-card-assets.mjs — do not edit; run \`just card-assets\`.
//
// The vCard PHOTO: src/assets/contact-photo.jpg at 256 × 256, baseline JPEG, base64.

export const PHOTO_JPEG_BASE64 =
  ${JSON.stringify(jpeg.toString('base64'))};
`,
);
console.log(`wrote src/lib/card-photo.js (${jpeg.length} bytes JPEG)`);
